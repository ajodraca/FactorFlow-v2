"""TC-COMP-345 / DAC-E1-S6-5: request-id middleware.

Every request gets a UUID generated by middleware, bound into the structured
logging context for the duration of the request so every log record emitted
while handling it carries the id as a field, and included in the response
(component design section 2.3, task plan T005).
"""

import logging

import pytest
from fastapi.testclient import TestClient

from factorflow.api.app import create_app


@pytest.fixture
def client(monkeypatch: pytest.MonkeyPatch) -> TestClient:
    monkeypatch.delenv("FACTORFLOW_DATABASE_URL", raising=False)
    monkeypatch.setenv("FACTORFLOW_DATABASE_URL", "postgresql://unused/unused")
    app = create_app()
    with TestClient(app) as test_client:
        yield test_client


def test_request_id_appears_in_every_log_record_and_the_response(
    client: TestClient, caplog: pytest.LogCaptureFixture
) -> None:
    with caplog.at_level(logging.INFO, logger="factorflow.api.routes.health"):
        response = client.get("/api/health")

    assert response.status_code == 200
    response_request_id = response.headers.get("x-request-id")
    assert response_request_id

    records_during_request = [
        record
        for record in caplog.records
        if getattr(record, "request_id", None) == response_request_id
    ]
    assert records_during_request, (
        "expected at least one log record carrying the response's request id"
    )


def test_two_requests_get_different_request_ids(client: TestClient) -> None:
    first = client.get("/api/health")
    second = client.get("/api/health")

    assert first.headers["x-request-id"] != second.headers["x-request-id"]
